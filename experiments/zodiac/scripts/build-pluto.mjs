// Regenerates src/astro/data/pluto-extended.js.
//
// astronomy-engine computes Pluto from a state table covering roughly 0 CE to 4000 CE.
// Outside that window it numerically integrates from the nearest table endpoint on
// every call, which takes 0.2 to 1 second per call: far too slow for a time scrubber.
// This script runs that same kind of integration once (astronomy-engine's public
// GravitySimulator, same 146-day step, perturbed by Sun/Jupiter/Saturn/Uranus/Neptune)
// and stores heliocentric J2000-equatorial positions every 1460 days, which the engine
// interpolates with a 4-point Lagrange cubic (error well under 1 arcsecond).
//
// Usage: node scripts/build-pluto.mjs

import * as A from 'astronomy-engine';
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'astro', 'data', 'pluto-extended.js');

const TABLE_MIN_TT = -730000; // astronomy-engine PlutoStateTable first entry
const TABLE_MAX_TT = 730000; //  ... and last entry
const DT = 146; // integration step (days), same as astronomy-engine
const SAMPLE_EVERY = 10; // keep every 10th step => 1460 days
const BACK_TO_TT = -1830000; // ~3010 BCE
const FORWARD_TO_TT = 1465000; // ~6011 CE

function integrate(startTt, endTt) {
  const t0 = A.AstroTime.FromTerrestrialTime(startTt);
  const start = A.BaryState(A.Body.Pluto, t0);
  const sim = new A.GravitySimulator(A.Body.SSB, t0, [start]);
  const dir = Math.sign(endTt - startTt);
  const samples = [];
  const record = (tt, s) => {
    const sun = A.BaryState(A.Body.Sun, A.AstroTime.FromTerrestrialTime(tt));
    samples.push([s.x - sun.x, s.y - sun.y, s.z - sun.z]);
  };
  record(startTt, start);
  const steps = Math.ceil(Math.abs(endTt - startTt) / DT / SAMPLE_EVERY) * SAMPLE_EVERY;
  for (let i = 1; i <= steps; i++) {
    const tt = startTt + dir * i * DT;
    const [s] = sim.Update(A.AstroTime.FromTerrestrialTime(tt));
    if (i % SAMPLE_EVERY === 0) record(tt, s);
  }
  return samples;
}

const fmt = (v) => v.toFixed(5).replace(/\.?0+$/, '');

// Backward segment: integrate from the table start toward the past, then reverse so
// samples are in increasing time order.
const back = integrate(TABLE_MIN_TT, BACK_TO_TT).reverse();
const backStart = TABLE_MIN_TT - (back.length - 1) * DT * SAMPLE_EVERY;
const fwd = integrate(TABLE_MAX_TT, FORWARD_TO_TT);

const body = `// GENERATED by scripts/build-pluto.mjs from astronomy-engine ${'2.1.19'} - do not edit.
// Heliocentric Pluto positions, J2000 equatorial (EQJ), AU, sampled every stepDays (TT days
// since J2000) outside astronomy-engine's fast Pluto table (~0 CE to ~4000 CE).
export const PLUTO_EXTENDED = {
  stepDays: ${DT * SAMPLE_EVERY},
  segments: [
    { startTt: ${backStart}, xyz: [${back.flat().map(fmt).join(',')}] },
    { startTt: ${TABLE_MAX_TT}, xyz: [${fwd.flat().map(fmt).join(',')}] },
  ],
};
`;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, body);
console.log(`wrote ${out}: ${back.length} + ${fwd.length} samples, ${(body.length / 1024).toFixed(1)} KiB`);
